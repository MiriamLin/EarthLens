METADATA_PATH = Path(__file__).resolve().parents[1] / "data" / "metadata.json"
FIELDS = ("type", "subtype", "temporal", "name", "definition", "units")


def load_metadata() -> list[dict[str, str]]:
    metadata = json.loads(METADATA_PATH.read_text(encoding="utf-8"))
    lookup = {item["key"]: item for item in metadata}
    return [
        {"key": key, **{field: lookup.get(key, {}).get(field, "") for field in FIELDS}}
        for key in DATA_KEYS
    ]
